/*
 * Create an autodt context.
 *
 * The context is used to store everything that is required while parsing the
 * device tree, e.g. storage for top-level handlers, stringlist pools.
 *
 * This function panics on failure.
 *
 * FIXME: Unfortunately, autodt can only support one context at a time. This
 * is because a 'context' variable is not passed to all the handlers. Still,
 * there are advantages to encapsulating everything in a context, e.g. the
 * memory used can be freed and used for other purposes once device tree
 * parsing is finished.
 */
dt_autodt_ctx_t *
dt_autodt_create_context(void);

/*
 * Get the autodt context.
 *
 * This function is called by the autogenerated handlers. The user should also
 * call this function to process the parsed device tree.
 */
dt_autodt_ctx_t *
dt_autodt_get_context(void);

/*
 * Destroy the current autodt context.
 *
 * This function panics on failure.
 */
void
dt_auto_destroy_context(void);

/*
 * Load a stringlist into the context.
 *
 * This function parses a stringlist 'sl' of size 'sl_size' bytes and unpacks
 * the strings for ease of use into an internal string pool. The number of
 * strings is written to 'len_out'.
 *
 * A pointer to the first unpacked string is returned.
 *
 * This function panics on failure.
 */
const char **
dt_auto_type_stringlist_load(const char *sl, count_t sl_size, count_t *len_out);
