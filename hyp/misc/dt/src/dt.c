static dt_tree_t	  dt_boot_tree;
static dt_auto_user_ctx_t dt_auto_user_ctx;
static dt_auto_root_t	 *dt_root;

char *dt_boot_dtb_ptr;

static void
dt_tree_init(dt_tree_t *tree, char *dtb)
{
	fdt_ret_t err = fdt_load_header(&tree->header, dtb);
	if (err != FDT_OK) {
		TRACE_AND_LOG(ERROR, PANIC, "dt: fdt_load_header returned {:d}",
			      (register_t)err);
		panic("dt_tree_init failed");
	}

	tree->dtb = dtb;
}

static void
dt_tree_main_pass(dt_tree_t *tree)
{
	fdt_parser_t parser;
	fdt_parser_setup(&parser, tree, NULL);

	parser.user_ctx.autodt = &dt_auto_user_ctx;

	// The autogenerated handlers expect the parser be at the state where
	// the node was just consumed.
	if (fdt_parser_next_node(&parser) != FDT_RET_NODE) {
		panic("dt: tree does not start with a node");
	}

	// FIXME: Free the memory once we're done with it, probably later in
	// boot_color_init.
	dt_autodt_create_context();

	dt_auto_root_parse(&parser);
	fdt_parser_next_end_tree(&parser);
}

void
dt_handle_boot_cold_init(void)
{
	dt_tree_t *tree = &dt_boot_tree;

	assert(dt_boot_dtb_ptr != NULL);
	assert(util_is_baligned((uintptr_t)dt_boot_dtb_ptr, 8U));

	dt_tree_init(tree, dt_boot_dtb_ptr);
	dt_tree_main_pass(tree);
	trigger_dt_init_finalise_event();
}

const char *
dt_get_string(dt_tree_t *tree, uint32_t offset)
{
	return tree->dtb + tree->header.off_dt_strings + offset;
}

count_t
dt_strlen_node_name(const char *s)
{
	count_t i = 0U;

	while (i < 32U) {
		if ((s[i] == '\0') || (s[i] == '@')) {
			break;
		}

		i++;
	}

	return i;
}

dt_tree_t *
dt_get_boot_tree(void)
{
	return &dt_boot_tree;
}

dt_auto_root_t *
dt_get_root(void)
{
	assert(dt_root != NULL);
	return dt_root;
}

void
dt_root_init_finalise(void)
{
	count_t root_count = dt_auto_root_get_count();
	assert(root_count != 0U);
	dt_root = dt_auto_root_get();

	TRACE_AND_LOG(ERROR, WARN, "dt: model {:s}",
		      (register_t)dt_root->model);
}

const char *
dt_get_memory_reservation_block(dt_tree_t *tree)
{
	return tree->dtb + tree->header.off_mem_rsvmap;
}
